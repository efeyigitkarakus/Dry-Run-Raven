export type UIKey = keyof typeof STR;

export function t(lang: UILang, key: UIKey): string {
  const entry = STR[key];
  return lang === 'en' ? entry[1] : entry[0];
}

export function tf(lang: UILang, key: UIKey, n: number | string): string {
  return `${n} ${t(lang, key)}`;
}
